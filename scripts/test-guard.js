/** The real PDF's layout (header block, 4-column rows, "Page k of M" footers); text joined like pdftotext -layout. */
function pdfText(routes, { date = PDF_DATE, rowsPerPage = 44, pages: pageFilter = null } = {}) {
    const pairs = routes.map((r) => r.split(' - '));
    const perPage = rowsPerPage * 2;
    const total = Math.max(1, Math.ceil(pairs.length / perPage));
    const col = (s, w) => s.padEnd(Math.max(w, s.length + 2));
    const pages = [];
    for (let p = 0; p < total; p++) {
        const chunk = pairs.slice(p * perPage, (p + 1) * perPage);
        const lines = p === 0 ? [
            `${col('Departure period:', 76)}Last run:`,
            `${col(`${date} 07:00:01 - ${date} 23:59:59 (CET)`, 76)}${date} 07:00:01 (CET)`,
            '',
            'Please note: synthetic test data generated by scripts/test-guard.js.',
            'Terms & Conditions',
            ''
        ] : [];
        lines.push(`    ${col('Departure City', 32)}${col('Arrival City', 30)}${col('Departure City', 30)}Arrival City`);
        for (let i = 0; i < rowsPerPage; i++) {
            const l = chunk[i], r = chunk[i + rowsPerPage];
            if (!l) break;
            lines.push(r ? `${col(l[0], 27)}${col(l[1], 32)}${col(r[0], 27)}${r[1]}` : `${col(l[0], 27)}${l[1]}`);
        }
        lines.push('', `${' '.repeat(50)}Page ${p + 1} of ${total}`);
        pages.push(lines.join('\n'));
    }
    return (pageFilter ? pages.filter((_, i) => pageFilter(i, total)) : pages).join('\n\f');
}

/** Minimal PDF (Courier, one text line per row) so pdftotext -layout reproduces the columns. ASCII only. */
function textPdf(text) {
    const objs = [];
    const add = (s) => { objs.push(s); return objs.length; };
    const font = add('<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>');
    const pagesId = add(null);
    const kids = [];
    for (const page of text.split('\f')) {
        const esc = (s) => s.replace(/[\\()]/g, (c) => '\\' + c);
        const body = `BT /F1 7 Tf 9 TL 20 820 Td ${page.split('\n').map((l) => `(${esc(l)}) Tj T*`).join(' ')} ET`;
        const content = add(`<< /Length ${Buffer.byteLength(body, 'latin1')} >>\nstream\n${body}\nendstream`);
        kids.push(add(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 ${font} 0 R >> >> /Contents ${content} 0 R >>`));
    }
    objs[pagesId - 1] = `<< /Type /Pages /Kids [${kids.map((k) => `${k} 0 R`).join(' ')}] /Count ${kids.length} >>`;
    const catalog = add(`<< /Type /Catalog /Pages ${pagesId} 0 R >>`);
    let out = '%PDF-1.4\n';
    const offsets = objs.map((o, i) => { const at = Buffer.byteLength(out, 'latin1'); out += `${i + 1} 0 obj\n${o}\nendobj\n`; return at; });
    const xref = Buffer.byteLength(out, 'latin1');
    out += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
    out += `trailer\n<< /Size ${objs.length + 1} /Root ${catalog} 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
    return Buffer.from(out, 'latin1');
}

// ------------------------------------------------------------------ layout variations
// Text-level changes of a generated PDF; each one changes ONE layout element (column headers, "Last run:", page footers).
const HEADER_LINE = /Departure City|Arrival City/;
const FOOTER_LINE = /Page \d+ of \d+/;
const mapLines = (re, fn) => (text) => text.split('\n').map((l) => (re.test(l) ? fn(l) : l)).join('\n');
// a dropped line keeps the page break (\f) that pdftotext puts in front of a page's first line
const dropLines = (re) => (text) => text.split('\n').flatMap((l) => (re.test(l) ? (l.startsWith('\f') ? ['\f'] : []) : [l])).join('\n');
const LAYOUT = {
    lowerHeaders: mapLines(HEADER_LINE, (l) => l.toLowerCase()),
    upperHeaders: mapLines(HEADER_LINE, (l) => l.toUpperCase()),
    fromTo: mapLines(HEADER_LINE, (l) => l.replace(/Departure City/g, 'From').replace(/Arrival City/g, 'To')),
    reworded: mapLines(HEADER_LINE, (l) => l.replace(/Departure City/g, 'Departure Airport').replace(/Arrival City/g, 'Arrival Airport')),
    noHeaders: dropLines(HEADER_LINE),
    noDepartureHeader: mapLines(HEADER_LINE, (l) => l.replace(/Departure City/g, '')),                 // "Arrival City" stays
    threeColumnHeader: mapLines(HEADER_LINE, (l) => l.replace(/ +Arrival City *$/, '')),                // 4th header cell missing
    headerMissingOnPage1: (text) => text.replace(/^.*Departure City.*\n/m, ''),                         // the other pages keep theirs
    slashFooters: (text) => text.replace(/Page (\d+) of (\d+)/g, 'Page $1/$2'),
    pageOnlyFooters: (text) => text.replace(/Page (\d+) of \d+/g, 'Page $1'),
    noFooters: dropLines(FOOTER_LINE),
    lastRunCapital: (text) => text.replace('Last run:', 'Last Run:'),
    lastRunSameLine: (text) => text.replace(/Last run:\n(.+?) {2,}(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} \(CET\))\n/, 'Last run: $2\n$1\n'),
    noLastRun: (text) => text.replace('Last run:', '').replace(/ {2,}\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2} \(CET\)\n/, '\n')
};
LAYOUT.everything = (text) => LAYOUT.noFooters(LAYOUT.noLastRun(LAYOUT.lowerHeaders(text)));
// What the ::warning:: line says for each kind of difference.
const SAYS = {
    headersMissing: /column headers are missing or different \(no line with these column headers found\)/,
    headersOdd: /column headers are missing or different \(unexpected header line "[^"]+"\)/,
    footersMissing: /"Page k of M" footers do not cover every page \(no "Page k of M" footer found\)/,
    lastRun: /"Last run:" date could not be parsed, so the date line on the site \(index\.html, README\.md\) was not updated/
};
// [label, change, what the warning says, does the date line move to the PDF date?]
const LAYOUT_CASES = [
    ['lower-case column headers', LAYOUT.lowerHeaders, SAYS.headersMissing, true],
    ['upper-case column headers', LAYOUT.upperHeaders, SAYS.headersMissing, true],
    ['"From / To" instead of "Departure City / Arrival City"', LAYOUT.fromTo, SAYS.headersMissing, true],
    ['reworded column headers ("Departure Airport / Arrival Airport")', LAYOUT.reworded, SAYS.headersMissing, true],
    ['column headers missing on every page', LAYOUT.noHeaders, SAYS.headersMissing, true],
    ['"Departure City" header missing on every page ("Arrival City" stays)', LAYOUT.noDepartureHeader, SAYS.headersOdd, true],
    ['header line with a missing column', LAYOUT.threeColumnHeader, SAYS.headersOdd, true],
    ['"Page k/M" footers', LAYOUT.slashFooters, SAYS.footersMissing, true],
    ['"Page k" footers', LAYOUT.pageOnlyFooters, SAYS.footersMissing, true],
    ['no footers', LAYOUT.noFooters, SAYS.footersMissing, true],
    ['"Last Run:" capitalization', LAYOUT.lastRunCapital, SAYS.lastRun, false],
    ['the date on the same line as "Last run:"', LAYOUT.lastRunSameLine, SAYS.lastRun, false],
    ['no "Last run" line', LAYOUT.noLastRun, SAYS.lastRun, false]
];

/** Temporary site copy whose data.js holds `previous` and whose index.html / README.md show PREV_DATE. */
function makeRoot(previous = BASE) {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'guard-test-'));
    for (const f of FILES) if (fs.existsSync(path.join(REPO, f))) fs.copyFileSync(path.join(REPO, f), path.join(root, f));
    const dp = path.join(root, 'data.js');
    fs.writeFileSync(dp, fs.readFileSync(dp, 'utf8').replace(RAW_BLOCK_RE, () => `    const rawFlightData = \`${previous.join('\n')}\``));
    const [y, m, d] = PREV_DATE.split('-');
    const ip = path.join(root, 'index.html');
    fs.writeFileSync(ip, fs.readFileSync(ip, 'utf8').replace(/All You Can Fly 最新空席データ（\d{4}年\d{1,2}月\d{1,2}日更新）/, `All You Can Fly 最新空席データ（${y}年${Number(m)}月${Number(d)}日更新）`));
    const rp = path.join(root, 'README.md');
    fs.writeFileSync(rp, fs.readFileSync(rp, 'utf8').replace(/## V2（\d{4}-\d{2}-\d{2}）/, `## V2（${PREV_DATE}）`));
    return root;
}
